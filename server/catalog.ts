// Keep type-specific startup environment separate from user-editable variables.
export function templateEnvironment(t: Ziyn): Record<string, string> {
  const env = Object.fromEntries(t.variables.map((v) => [v.key, v.default]));
  const types: Record<string, string> = {
    paper: "PAPER",
    purpur: "PURPUR",
    fabric: "FABRIC",
    forge: "FORGE",
    neoforge: "NEOFORGE",
    vanilla: "VANILLA",
    spigot: "SPIGOT",
    bedrock: "BEDROCK",
  };
  if (types[t.id]) env.TYPE = types[t.id];
  if (t.id === "velocity") env.TYPE = "VELOCITY";
  return env;
}
